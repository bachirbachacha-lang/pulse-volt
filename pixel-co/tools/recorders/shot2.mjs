import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const [src,out,w,h,pre]=process.argv.slice(2);
const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
const p=await b.newPage({viewport:{width:+w,height:+h},deviceScaleFactor:+w<500?3:2});
const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('console',m=>m.type()==='error'&&errs.push(m.text()));
await p.goto('file://'+src);await p.waitForTimeout(1500);
const go=async y=>{await p.evaluate(y=>scrollTo({top:y,behavior:'instant'}),y);await p.waitForTimeout(500)};
await p.screenshot({path:out+'/'+pre+'1-home.png'});
await go(await p.evaluate(()=>document.querySelector('#menu').offsetTop-70));
await p.screenshot({path:out+'/'+pre+'2-menu.png'});
await p.click('[data-open="isb"]');await p.click('[data-g="milk"][data-v="oat"]');await p.click('[data-g="size"][data-v="lg"]');await p.waitForTimeout(1200);
await p.screenshot({path:out+'/'+pre+'3-customise.png'});
await p.click('#addBtn');await p.waitForTimeout(600);
await p.fill('#name','نورة');
await go(await p.evaluate(()=>document.querySelector('#checkout').getBoundingClientRect().top+scrollY-70));
await p.screenshot({path:out+'/'+pre+'4-order.png'});
await go(await p.evaluate(()=>document.querySelector('.shop-sees').getBoundingClientRect().top+scrollY-200));
await p.screenshot({path:out+'/'+pre+'5-whatsapp.png'});
console.log('errors:',errs,'overflow:',await p.evaluate(()=>document.documentElement.scrollWidth));
await b.close();
