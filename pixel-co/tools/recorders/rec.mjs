import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
const [src,dir]=process.argv.slice(2);
const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
const ctx=await b.newContext({viewport:{width:390,height:844},deviceScaleFactor:3,hasTouch:true,isMobile:true});
const p=await ctx.newPage();
await p.goto('file://'+src);await p.waitForTimeout(1500);
const cdp=await ctx.newCDPSession(p);const frames=[];
cdp.on('Page.screencastFrame',async f=>{frames.push({t:f.metadata.timestamp,d:f.data});await cdp.send('Page.screencastFrameAck',{sessionId:f.sessionId}).catch(()=>{})});
await cdp.send('Page.startScreencast',{format:'jpeg',quality:88,maxWidth:1170,maxHeight:2532,everyNthFrame:1});
const W=ms=>p.waitForTimeout(ms);
const glide=async(to,ms=1400)=>{await p.evaluate(([to,ms])=>new Promise(r=>{const s=scrollY,t0=performance.now();const e=x=>x<.5?4*x*x*x:1-Math.pow(-2*x+2,3)/2;(function f(n){const k=Math.min(1,(n-t0)/ms);scrollTo(0,s+(to-s)*e(k));k<1?requestAnimationFrame(f):r()})(t0)}),[to,ms]);};
const top=sel=>p.evaluate(s=>document.querySelector(s).getBoundingClientRect().top+scrollY,sel);
await W(2200);
await glide((await top('#menu'))-70,1600);await W(1200);
await glide((await top('#menu'))+260,900);await W(700);
await p.tap('[data-open="isb"]');await W(1500);
await p.tap('[data-g="size"][data-v="lg"]');await W(900);
await p.tap('[data-g="milk"][data-v="oat"]');await W(1300);
await p.tap('[data-g="extra"][data-v="foam"]');await W(1300);
await p.tap('#addBtn');await W(1400);
await glide((await top('#checkout'))-70,1600);await W(1500);
await p.tap('[data-m="30"]');await W(800);
await p.tap('#name');await p.keyboard.type('Noura',{delay:120});await W(600);
await glide((await top('.shop-sees'))-150,1500);await W(3200);
await cdp.send('Page.stopScreencast');await W(200);
let list='';frames.forEach((f,i)=>{const n=dir+'/f'+String(i).padStart(5,'0')+'.jpg';fs.writeFileSync(n,Buffer.from(f.d,'base64'));const dur=i<frames.length-1?frames[i+1].t-f.t:1;list+="file '"+n+"'\nduration "+dur.toFixed(4)+"\n"});
list+="file '"+dir+'/f'+String(frames.length-1).padStart(5,'0')+".jpg'\n";
fs.writeFileSync(dir+'/list.txt',list);console.log('frames',frames.length,'secs',(frames.at(-1).t-frames[0].t).toFixed(1));
await b.close();
